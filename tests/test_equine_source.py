"""Regression checks for horse/donkey expansion without Second Life runtime."""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "DreamFarm_Herd.lsl"
GENERATED = ROOT / "lsl" / "DreamFarm_Herd.lsl"
STABLE = ROOT / "experimental" / "DreamFarm_EquineStable.lsl"


class EquineSourceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.herd = SOURCE.read_text(encoding="utf-8")
        cls.stable = STABLE.read_text(encoding="utf-8")

    def test_generated_herd_is_current(self):
        from tools.build import expand
        expected = "// GENERATED by tools/build.py. Edit src/, then rebuild.\n" + expand(SOURCE)
        self.assertEqual(GENERATED.read_text(encoding="utf-8"), expected)

    def test_species_and_gestation_are_aligned(self):
        expected = 6
        for label in ("SPECIES", "MATURE", "ADULT_WEIGHT", "GESTATION"):
            match = re.search(r"list " + label + r"=\[([^\]]+)\];", self.herd)
            self.assertIsNotNone(match, label)
            self.assertEqual(len(match.group(1).split(",")), expected, label)
        self.assertIn('"Horse","Donkey"', self.herd)
        self.assertIn("whole(a,2,0,5)", self.herd)

    def test_dialogs_obey_twelve_button_limit(self):
        for match in re.finditer(r'if\(p=="(?:manage|equines)"\)return \[([^\]]+)\];', self.herd):
            self.assertLessEqual(len(re.findall(r'"[^"]+"', match.group(1))), 12)
        # Stable menu is defined by llDialog, not a named function return.
        stable = re.search(r'llDialog\(who,[^\n]*\[([^\]]+)\],CHANNEL\)', self.stable)
        self.assertIsNotNone(stable)
        self.assertLessEqual(len(re.findall(r'"[^"]+"', stable.group(1))), 12)

    def test_stable_has_no_double_accounting(self):
        self.assertIn("stableManureEnabled=FALSE", self.stable)
        self.assertIn("careAccountingMode=0", self.stable)
        self.assertIn("EQUINE_CHECK", self.stable)
        self.assertIn("EQUINE_RESULT", self.herd)


if __name__ == "__main__":
    unittest.main()
