"""Expand our local includes; generated lsl/ files paste directly into SL."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def expand(path):
    text = path.read_text()
    return re.sub(r'^// @include ([\w.]+)$', lambda m: expand(path.parent / m[1]), text, flags=re.M)

def build(check=False):
    for path in sorted((ROOT / 'src').glob('DreamFarm_*.lsl')):
        content = '// GENERATED by tools/build.py. Edit src/, then rebuild.\n' + expand(path)
        dest = ROOT / 'lsl' / path.name
        if check:
            assert dest.read_text() == content, f'Stale generated file: {dest}'
        else:
            dest.write_text(content)

if __name__ == '__main__':
    import sys
    build('--check' in sys.argv)
